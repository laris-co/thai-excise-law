def expand(q):
    """Return (expanded question, legal terms added)."""
    added = []
    for pat, add, skip in _RULES:
        if pat.search(q) and not skip.search(q) and add not in added:
            added.append(add)
    return (f"{q} {' '.join(added)}" if added else q), added
